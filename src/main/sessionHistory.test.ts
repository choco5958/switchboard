import { mkdirSync, mkdtempSync, rmSync, utimesSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { afterEach, beforeEach, describe, expect, test } from 'vitest'
import type { PastSession } from '../shared/types'
import { claudeConfigDir, loadSessions, parseTranscript, searchSessions, sessionHistory } from './sessionHistory'

const ID_A = '11111111-1111-4111-8111-111111111111'
const ID_B = '22222222-2222-4222-8222-222222222222'
const ID_C = '33333333-3333-4333-8333-333333333333'

const user = (content: unknown, extra: Record<string, unknown> = {}) =>
  JSON.stringify({ type: 'user', cwd: '/work/shop', gitBranch: 'main', message: { role: 'user', content }, ...extra })
const assistant = (text: string) => JSON.stringify({ type: 'assistant', cwd: '/work/shop', message: { role: 'assistant', content: [{ type: 'text', text }] } })
const toolUse = () => JSON.stringify({ type: 'assistant', cwd: '/work/shop', message: { role: 'assistant', content: [{ type: 'tool_use', id: 't1', name: 'Bash', input: {} }] } })

const parse = (lines: string[], extra: Partial<Parameters<typeof parseTranscript>[0]> = {}) => {
  const head = lines.join('\n') + '\n'
  return parseTranscript({ id: ID_A, folder: '-work-shop', head, tail: '', whole: true, size: Buffer.byteLength(head), mtime: 1000, ...extra })
}

let config = ''
beforeEach(() => {
  config = mkdtempSync(join(tmpdir(), 'switchboard-sessions-'))
  process.env.CLAUDE_CONFIG_DIR = config
})
afterEach(() => {
  delete process.env.CLAUDE_CONFIG_DIR
  rmSync(config, { recursive: true, force: true })
})

function transcript(folder: string, id: string, lines: string[], mtimeSec: number): string {
  mkdirSync(join(config, 'projects', folder), { recursive: true })
  const path = join(config, 'projects', folder, `${id}.jsonl`)
  writeFileSync(path, lines.join('\n') + '\n')
  utimesSync(path, mtimeSec, mtimeSec)
  return path
}

describe('parseTranscript', () => {
  test('the first real prompt is the title; command, meta, reminder and tool records are skipped', () => {
    const session = parse([
      JSON.stringify({ type: 'file-history-snapshot', snapshot: {} }),
      user('Caveat: messages below were generated by the user', { isMeta: true }),
      user('<command-name>/clear</command-name>\n<command-message>clear</command-message>'),
      user('<local-command-stdout></local-command-stdout>'),
      user('<system-reminder>context</system-reminder>'),
      user([{ type: 'tool_result', tool_use_id: 't0', content: 'ok' }]),
      user('Sub agent work', { isSidechain: true }),
      user([{ type: 'text', text: '  Fix the\n  checkout   page  ' }]),
      toolUse(),
      assistant('Done: the checkout page loads again.'),
      'not json at all',
      '{"half": ',
    ])
    expect(session).toMatchObject({
      id: ID_A,
      cwd: '/work/shop',
      project: 'shop',
      folder: '-work-shop',
      branch: 'main',
      title: 'Fix the checkout page',
      snippet: 'Done: the checkout page loads again.',
      messages: 2,
      approximate: false,
      updatedAt: 1000,
    })
  })

  test('a long prompt is cut to one line of about 120 characters', () => {
    const session = parse([user(`${'word '.repeat(60)}\nsecond line`)])
    expect(session!.title.length).toBeLessThanOrEqual(120)
    expect(session!.title).not.toContain('\n')
    expect(session!.title.endsWith('…')).toBe(true)
  })

  test('the snippet is the latest prompt or reply', () => {
    expect(parse([user('first ask'), assistant('an answer'), user('a follow up')])!.snippet).toBe('a follow up')
  })

  test('with no prompt in what was read, the title falls back to the AI title', () => {
    const session = parse([JSON.stringify({ type: 'ai-title', aiTitle: 'Checkout repair' }), assistant('hello')])
    expect(session!.title).toBe('Checkout repair')
  })

  test('a transcript with no conversation is left out', () => {
    expect(parse([JSON.stringify({ type: 'file-history-snapshot', snapshot: {} }), user('<command-name>/exit</command-name>')])).toBeNull()
    expect(parse([])).toBeNull()
  })

  test('only the ends of a long file: part lines are dropped and the count is scaled', () => {
    const head = `${user('the opening ask')}\n${assistant('first answer')}\n{"type":"user","mess`
    const tail = `ge":"cut"}\n${assistant('the last words')}\n`
    const session = parseTranscript({ id: ID_A, folder: '-work-shop', head, tail, whole: false, size: (head.length + tail.length) * 10, mtime: 5 })
    expect(session).toMatchObject({ title: 'the opening ask', snippet: 'the last words', approximate: true, messages: 30 })
  })
})

describe('loadSessions', () => {
  test('reads CLAUDE_CONFIG_DIR/projects, newest first, and skips odd files', async () => {
    transcript('-work-shop', ID_A, [user('older shop work'), assistant('ok')], 1_000_000)
    transcript('-work-blog', ID_B, [user('write the blog post', { cwd: '/work/blog', gitBranch: 'draft' }), assistant('ok')], 2_000_000)
    transcript('-work-blog', 'agent-abc123', [user('side work')], 3_000_000)
    transcript('-work-blog', 'not a session id', [user('odd name')], 3_000_000)
    writeFileSync(join(config, 'projects', '-work-blog', 'notes.txt'), 'x')
    transcript('-work-empty', ID_C, [JSON.stringify({ type: 'file-history-snapshot' })], 3_000_000)

    expect(claudeConfigDir()).toBe(config)
    const { total, sessions } = await loadSessions()
    expect(total).toBe(3)
    expect(sessions.map(s => s.id)).toEqual([ID_B, ID_A])
    expect(sessions[0]).toMatchObject({ cwd: '/work/blog', project: 'blog', branch: 'draft', title: 'write the blog post', updatedAt: 2_000_000_000 })
  })

  test('a large transcript is read by its ends', async () => {
    const filler = assistant('x'.repeat(1000))
    const lines = [user('the very first ask'), ...Array.from({ length: 1000 }, () => filler), assistant('the final reply')]
    transcript('-work-shop', ID_A, lines, 1_000_000)
    const { sessions } = await loadSessions(config)
    expect(sessions[0]).toMatchObject({ title: 'the very first ask', snippet: 'the final reply', approximate: true })
    expect(sessions[0]!.messages).toBeGreaterThan(900)
    expect(sessions[0]!.messages).toBeLessThan(1100)
  })

  test('a changed transcript is read again', async () => {
    const path = transcript('-work-shop', ID_A, [user('first version')], 1_000_000)
    expect((await loadSessions(config)).sessions[0]!.title).toBe('first version')
    writeFileSync(path, `${user('second version, longer')}\n`)
    utimesSync(path, 1_000_100, 1_000_100)
    expect((await loadSessions(config)).sessions[0]!.title).toBe('second version, longer')
  })

  test('no projects folder: nothing found', async () => {
    expect(await loadSessions(join(config, 'missing'))).toEqual({ total: 0, sessions: [] })
    expect(await sessionHistory('', join(config, 'missing'))).toEqual({ total: 0, sessions: [] })
  })
})

describe('searchSessions', () => {
  const at = (id: string, updatedAt: number, fields: Partial<PastSession>): PastSession => ({
    id,
    agent: 'claude',
    cwd: '',
    project: '',
    folder: '',
    branch: '',
    title: '',
    snippet: '',
    messages: 1,
    approximate: false,
    updatedAt,
    ...fields,
  })
  const all = [
    at('a', 1, { title: 'Fix the Checkout page', cwd: '/work/shop', project: 'shop', folder: '-work-shop' }),
    at('b', 3, { title: 'Blog post', snippet: 'the checkout story', branch: 'feature/blog' }),
    at('c', 2, { title: 'Release notes', project: 'shop', branch: 'release-1.2' }),
  ]

  test('matches title, snippet, folder, project and branch, ignoring case; newest first', () => {
    expect(searchSessions(all, 'CHECKOUT').map(s => s.id)).toEqual(['b', 'a'])
    expect(searchSessions(all, 'shop').map(s => s.id)).toEqual(['c', 'a'])
    expect(searchSessions(all, 'feature/').map(s => s.id)).toEqual(['b'])
    expect(searchSessions(all, '-work-').map(s => s.id)).toEqual(['a'])
  })

  test('every word must match somewhere', () => {
    expect(searchSessions(all, 'shop release').map(s => s.id)).toEqual(['c'])
    expect(searchSessions(all, 'shop nothing')).toEqual([])
  })

  test('an empty query lists all, capped', () => {
    expect(searchSessions(all, '  ').map(s => s.id)).toEqual(['b', 'c', 'a'])
    expect(searchSessions(all, '', 2).map(s => s.id)).toEqual(['b', 'c'])
  })
})
